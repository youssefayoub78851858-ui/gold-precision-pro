"use strict";

// Historical simulation uses the same V2 engine as /api/analyze.
// Candles are oldest first; no live orders are sent.
const { generateHistoricalSignals } = require("./strategy");

function backtest(candles, signals, options = {}) {
  const rr = options.rr ?? 2;
  const spread = options.spread ?? 0.40;
  const risk = options.risk ?? 1;

  if (!Array.isArray(candles) || !Array.isArray(signals)) {
    throw new Error("Candles and signals must be arrays");
  }
  if (!(Number.isFinite(rr) && rr > 0 && Number.isFinite(spread) && spread >= 0 &&
      Number.isFinite(risk) && risk > 0)) {
    throw new Error("Invalid test settings");
  }

  const orderedSignals = [...signals]
    .filter(s => s && Number.isInteger(s.index))
    .sort((a, b) => a.index - b.index);
  const trades = [];
  let lastExitIndex = -1;
  let openAtEnd = 0;

  for (const s of orderedSignals) {
    if (s.index <= lastExitIndex) continue;
    if (s.side !== "BUY" && s.side !== "SELL") continue;
    if (s.index < 0 || s.index >= candles.length - 1) continue;

    const entryIndex = s.index + 1;
    const entry = Number(candles[entryIndex].open);
    const stop = Number(s.stop);
    const riskDistance = Math.abs(entry - stop);
    if (!Number.isFinite(entry) || !Number.isFinite(stop) || !(riskDistance > 0)) continue;
    if (s.side === "BUY" ? stop >= entry : stop <= entry) continue;

    const target = Number.isFinite(Number(s.target))
      ? Number(s.target)
      : s.side === "BUY" ? entry + riskDistance * rr : entry - riskDistance * rr;
    if (s.side === "BUY" ? target <= entry : target >= entry) continue;

    let closed = false;
    for (let i = entryIndex; i < candles.length; i++) {
      const bar = candles[i];
      const open = Number(bar.open), high = Number(bar.high), low = Number(bar.low);
      if (![open, high, low].every(Number.isFinite) || low > high || open < low || open > high) {
        throw new Error("Invalid OHLC candle at index " + i);
      }

      let exitPrice = null;
      let result = null;
      if (i > entryIndex && (s.side === "BUY" ? open <= stop : open >= stop)) {
        exitPrice = open;
        result = "LOSS";
      } else if (i > entryIndex && (s.side === "BUY" ? open >= target : open <= target)) {
        exitPrice = target;
        result = "WIN";
      } else {
        const hitStop = s.side === "BUY" ? low <= stop : high >= stop;
        const hitTarget = s.side === "BUY" ? high >= target : low <= target;
        // If both levels occur in one candle, use the conservative stop-first fill.
        if (hitStop) {
          exitPrice = stop;
          result = "LOSS";
        } else if (hitTarget) {
          exitPrice = target;
          result = "WIN";
        }
      }

      if (result !== null) {
        const grossR = (s.side === "BUY" ? exitPrice - entry : entry - exitPrice) / riskDistance;
        const netR = grossR - spread / riskDistance;
        trades.push({ result, netR, grossR, side: s.side, entry, stop, target,
          exitPrice, signalIndex: s.index, entryIndex, exitIndex: i });
        lastExitIndex = i;
        closed = true;
        break;
      }
    }

    if (!closed) {
      openAtEnd = 1;
      break;
    }
  }

  const count = trades.length;
  const wins = trades.filter(t => t.netR > 0).length;
  const losses = count - wins;
  const totalR = trades.reduce((sum, t) => sum + t.netR, 0);
  const profit = trades.reduce((sum, t) => sum + Math.max(t.netR, 0), 0);
  const loss = trades.reduce((sum, t) => sum + Math.max(-t.netR, 0), 0);
  return {
    engine: "Gold Precision Pro V2",
    trades: count,
    generatedSignals: signals.length,
    wins,
    losses,
    netProfitableTrades: wins,
    winRate: count ? +(wins / count * 100).toFixed(2) : 0,
    profitFactor: loss ? +(profit / loss).toFixed(2) : null,
    totalR: +totalR.toFixed(2),
    estimatedPnL: +(totalR * risk).toFixed(2),
    estimatedPnLIsHypothetical: true,
    tradesDetail: trades,
    openAtEnd,
    auditNotes: [
      "Signals are generated by the same V2 EMA/RSI/ATR and M15/H1/H4 agreement rules as live analysis.",
      "At each M15 close, only higher-timeframe candles already closed at that time are used.",
      "Entries are at the next M15 candle open; overlapping positions are skipped.",
      "If stop and target are both touched in one candle, the stop is assumed first.",
      "Adverse gaps across a stop are filled at candle open; spread is fixed and approximate.",
      "Commissions and slippage are not modeled. Results do not guarantee future profitability."
    ]
  };
}

function backtestFrames(frames, options = {}) {
  if (!frames || !Array.isArray(frames["15min"])) throw new Error("Missing 15min candles");
  const signals = generateHistoricalSignals(frames);
  const candles = [...frames["15min"]]
    .map(c => ({ ...c, _time: Date.parse(c.datetime.includes("T") ? c.datetime : c.datetime.replace(" ", "T") + "Z") }))
    .filter(c => Number.isFinite(c._time))
    .sort((a, b) => a._time - b._time)
    .map(({ _time, ...c }) => c);
  return backtest(candles, signals, options);
}

module.exports = { backtest, backtestFrames };
